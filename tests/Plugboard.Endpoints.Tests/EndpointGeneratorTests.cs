        """);

    [Test]
    public Task Generate_WithRootNamespaceProperty_ShouldEmitIntoRootNamespace() =>
        Generate(HealthEndpoint, """
            // <auto-generated/>
            #nullable enable

            using Microsoft.AspNetCore.Builder;
            using Microsoft.AspNetCore.Routing;

            namespace My.Custom.Root;

            internal static class EndpointRegistrationExtensions
            {
                /// <summary>Maps every endpoint and endpoint group declared in this assembly.</summary>
                internal static IEndpointRouteBuilder RegisterEndpoints(this IEndpointRouteBuilder app)
                {
                    global::TestProject.Features.Health.HealthEndpoint.MapEndpoint(app);
                    return app;
                }
            }
            """, rootNamespace: "My.Custom.Root");

    [AssertionMethod]
    private static Task Generate(string source, string? expected = null, string rootNamespace = "TestAssembly")
    {
        var test = new CSharpSourceGeneratorTest<EndpointGenerator, DefaultVerifier>
        {
            TestCode = source,
            ReferenceAssemblies = TestReferences.Net80AspNetCore
        };
        test.TestState.AdditionalReferences.Add(typeof(EndpointAttribute).Assembly);

        // build_property.* values reach the generator through a global analyzer config, exactly as MSBuild passes them.
        test.TestState.AnalyzerConfigFiles.Add(("/.globalconfig", $"""
            is_global = true
            build_property.RootNamespace = {rootNamespace}
            """));

        // No expected text means the generator must emit nothing; the framework asserts the exact set of generated files.
        if (expected is not null)
        {
            test.TestState.GeneratedSources.Add((typeof(EndpointGenerator), "EndpointRegistration.g.cs",
                SourceText.From(expected.ReplaceLineEndings("\n"), Encoding.UTF8)));
        }

        return test.RunAsync();
    }
}
