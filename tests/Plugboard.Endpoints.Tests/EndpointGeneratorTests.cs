using System.Text;
using JetBrains.Annotations;
using Microsoft.CodeAnalysis.CSharp.Testing;
using Microsoft.CodeAnalysis.Testing;
using Microsoft.CodeAnalysis.Text;
using NUnit.Framework;
using Plugboard.Endpoints.Generator;

namespace Plugboard.Endpoints.Tests;

[TestFixture]
internal sealed class EndpointGeneratorTests
{
    private const string HealthEndpoint = """

        namespace TestProject.Features.Health
        {
            using Plugboard;
            using Microsoft.AspNetCore.Routing;

            [Endpoint]
            public static class HealthEndpoint
            {
                public static void MapEndpoint(IEndpointRouteBuilder app) { }
            }
        }
        """;

    private const string TodoGroupWithEndpoint = """

        namespace TestProject.Features.Todos
        {
            using Plugboard;
            using Microsoft.AspNetCore.Routing;

            [EndpointGroup]
            public static class TodoGroup
            {
                public static void Configure(RouteGroupBuilder group) { }
            }

            [Endpoint(typeof(TodoGroup))]
            public sealed class GetTodoEndpoint
            {
                public static void MapEndpoint(IEndpointRouteBuilder app) { }
            }
        }
        """;

    [Test]
    public Task Generate_WithStandaloneEndpoint_ShouldEmitRegistration() =>
        Generate(HealthEndpoint, """
            // <auto-generated/>
            #nullable enable

            using Microsoft.AspNetCore.Builder;
            using Microsoft.AspNetCore.Routing;

            namespace TestAssembly;

            internal static class EndpointRegistrationExtensions
            {
                /// <summary>Maps every endpoint and endpoint group declared in this assembly.</summary>
                internal static IEndpointRouteBuilder RegisterEndpoints(this IEndpointRouteBuilder app)
                {
                    global::TestProject.Features.Health.HealthEndpoint.MapEndpoint(app);
                    return app;
                }
            }
            """);

    [Test]
    public Task Generate_WithGroupedEndpoint_ShouldEmitGroupRegistration() =>
        Generate(TodoGroupWithEndpoint, """
            // <auto-generated/>
            #nullable enable

            using Microsoft.AspNetCore.Builder;
            using Microsoft.AspNetCore.Routing;

            namespace TestAssembly;

            internal static class EndpointRegistrationExtensions
            {
                /// <summary>Maps every endpoint and endpoint group declared in this assembly.</summary>
                internal static IEndpointRouteBuilder RegisterEndpoints(this IEndpointRouteBuilder app)
                {
                    app.RegisterTodoGroup();
                    return app;
                }

                /// <summary>Maps <see cref="global::TestProject.Features.Todos.TodoGroup"/> and the endpoints declared for it.</summary>
                internal static IEndpointRouteBuilder RegisterTodoGroup(this IEndpointRouteBuilder app)
                {
                    RouteGroupBuilder group = app.MapGroup(string.Empty);
                    global::TestProject.Features.Todos.TodoGroup.Configure(group);
                    global::TestProject.Features.Todos.GetTodoEndpoint.MapEndpoint(group);
                    return app;
                }
            }
            """);

    [Test]
    public Task Generate_WithGroupWithoutEndpoints_ShouldStillRegisterGroup()
    {
        const string source = """

            namespace TestProject.Features.Admin
            {
                using Plugboard;
                using Microsoft.AspNetCore.Routing;

                [EndpointGroup]
                public static class AdminGroup
                {
                    public static void Configure(RouteGroupBuilder group) { }
                }
            }
            """;

        return Generate(source, """
            // <auto-generated/>
            #nullable enable

            using Microsoft.AspNetCore.Builder;
            using Microsoft.AspNetCore.Routing;

            namespace TestAssembly;

            internal static class EndpointRegistrationExtensions
            {
                /// <summary>Maps every endpoint and endpoint group declared in this assembly.</summary>
                internal static IEndpointRouteBuilder RegisterEndpoints(this IEndpointRouteBuilder app)
                {
                    app.RegisterAdminGroup();
                    return app;
                }

                /// <summary>Maps <see cref="global::TestProject.Features.Admin.AdminGroup"/> and the endpoints declared for it.</summary>
                internal static IEndpointRouteBuilder RegisterAdminGroup(this IEndpointRouteBuilder app)
                {
                    RouteGroupBuilder group = app.MapGroup(string.Empty);
                    global::TestProject.Features.Admin.AdminGroup.Configure(group);
                    return app;
                }
            }
            """);
    }

    [Test]
    public Task Generate_WithBothKinds_ShouldEmitAll() =>
        Generate(HealthEndpoint + TodoGroupWithEndpoint, """
