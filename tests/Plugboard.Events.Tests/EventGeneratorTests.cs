    /// <summary>Generated files by hint name, and the interceptor bodies with the opaque location replaced by a placeholder.</summary>
    private sealed record GeneratorRun(IReadOnlyDictionary<string, string> Files)
    {
        public string Interceptors => Files.TryGetValue("SubscriptionInterceptors.g.cs", out string? text)
            ? string.Join("\n", Regex.Replace(text, """InterceptsLocation\(1, "[^"]+"\)""", """InterceptsLocation(1, "<location>")""")
                .Split('\n')
                .SkipWhile(static line => !line.Contains("[global::System.Runtime.CompilerServices.InterceptsLocation(", StringComparison.Ordinal))
                .TakeWhile(static line => line != "    }")
                .Select(static line => line.Length > 8 ? line[8..] : line.TrimStart()))
            : string.Empty;
    }

    [AssertionMethod]
    private static async Task<GeneratorRun> Generate(string source, string rootNamespace = "TestAssembly", string? referencedSource = null)
    {
        ImmutableArray<MetadataReference> references = [
            .. await TestReferences.Net100.ResolveAsync(LanguageNames.CSharp, CancellationToken.None),
            MetadataReference.CreateFromFile(typeof(EventAttribute).Assembly.Location),
            MetadataReference.CreateFromFile(typeof(IServiceCollection).Assembly.Location),
            MetadataReference.CreateFromFile(typeof(DbContext).Assembly.Location)];
        var parseOptions = CSharpParseOptions.Default.WithFeatures([new KeyValuePair<string, string>("InterceptorsNamespaces", "Plugboard.Events.Generated")]);
        var compilationOptions = new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, nullableContextOptions: NullableContextOptions.Enable);

        if (referencedSource is not null)
        {
            // Compiled to a separate assembly so its types reach the generator as metadata symbols, as a project reference would.
            references = references.Add(CSharpCompilation.Create("TestReferencedAssembly",
                [CSharpSyntaxTree.ParseText(referencedSource, parseOptions)], references, compilationOptions).ToMetadataReference());
        }

        var compilation = CSharpCompilation.Create("TestAssembly",
            [CSharpSyntaxTree.ParseText(source, parseOptions)], references, compilationOptions);

        GeneratorDriver driver = CSharpGeneratorDriver.Create(
            [new EventGenerator().AsSourceGenerator()],
            parseOptions: parseOptions,
            optionsProvider: new RootNamespaceOptions(rootNamespace));
        driver = driver.RunGeneratorsAndUpdateCompilation(compilation, out Compilation output, out ImmutableArray<Diagnostic> generatorDiagnostics, CancellationToken.None);

        Assert.That(generatorDiagnostics, Is.Empty);
        // The source under test may be deliberately invalid (PB rules); generated code must compile without even a warning,
        // because consumers build with TreatWarningsAsErrors.
        Diagnostic[] generated = [.. output.GetDiagnostics().Where(static d =>
            d.Severity >= DiagnosticSeverity.Warning && d.Location.SourceTree?.FilePath.EndsWith(".g.cs", StringComparison.Ordinal) == true)];
        Assert.That(generated, Is.Empty);

        GeneratorDriverRunResult result = driver.GetRunResult();
        var files = result.Results.SelectMany(static r => r.GeneratedSources)
            .ToDictionary(static s => s.HintName, static s => s.SourceText.ToString().ReplaceLineEndings("\n"), StringComparer.Ordinal);
        return new GeneratorRun(files);
    }

    /// <summary>build_property.RootNamespace as MSBuild passes it to the generator.</summary>
    private sealed class RootNamespaceOptions(string rootNamespace) : AnalyzerConfigOptionsProvider
    {
        public override AnalyzerConfigOptions GlobalOptions { get; } = new Options(rootNamespace);

        public override AnalyzerConfigOptions GetOptions(SyntaxTree tree) => GlobalOptions;

        public override AnalyzerConfigOptions GetOptions(AdditionalText textFile) => GlobalOptions;

        private sealed class Options(string rootNamespace) : AnalyzerConfigOptions
        {
            public override bool TryGetValue(string key, out string value)
            {
                value = rootNamespace;
                return key == "build_property.RootNamespace";
            }
        }
    }
