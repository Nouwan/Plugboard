    [Test]
    public async Task Generate_WithTwoSubscribeCalls_ShouldEmitOneInterceptorEach()
    {
        GeneratorRun run = await Generate(OrderPlacedEvent + """
            namespace TestProject.Orders
            {
                using System.Threading.Tasks;
                using Plugboard.Events;

                public static class OrderHandlers
                {
                    [Subscribe]
                    public static void Subscriptions(SubscriptionBuilder events)
                    {
                        events.Subscribe("send-confirmation", (OrderPlaced e) => Task.CompletedTask);
                        events.Subscribe("update-stock", (OrderPlaced e) => Task.CompletedTask);
