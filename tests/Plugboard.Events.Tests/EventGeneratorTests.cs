        Assert.That(Regex.Count(run.Files["SubscriptionInterceptors.g.cs"], Regex.Escape("[global::System.Runtime.CompilerServices.InterceptsLocation(")), Is.EqualTo(2));
        Assert.That(run.Files["SubscriptionInterceptors.g.cs"], Does.Contain("Subscribe0(").And.Contain("Subscribe1("));
    }

