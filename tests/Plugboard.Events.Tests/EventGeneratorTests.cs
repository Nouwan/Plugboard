using System.Collections.Immutable;
using System.Text.RegularExpressions;
using JetBrains.Annotations;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Testing;
using Microsoft.Extensions.DependencyInjection;
using NUnit.Framework;
using Plugboard.Events.Generator;

namespace Plugboard.Events.Tests;

/// <summary>
/// Runs the generator with interceptors enabled and compiles the result, so a wrong [InterceptsLocation] or a
/// non-compiling rewrite fails here, not in a consumer.
/// </summary>
[TestFixture]
internal sealed class EventGeneratorTests
{
    private const string OrderPlacedEvent = """
        namespace TestProject.Orders
        {
            using Plugboard.Events;

            [Event("order.placed")]
            public sealed partial record OrderPlaced(int OrderId);
        }

        """;

    private const string OrderPlacedPart = """
        // <auto-generated/>
        #nullable enable

        namespace TestProject.Orders
        {
            partial record OrderPlaced : global::Plugboard.Events.IEvent
            {
                public static string EventName => "order.placed";
            }
        }
        """;

    private const string Registration = """
        // <auto-generated/>
        #nullable enable

        using Microsoft.Extensions.DependencyInjection;
        using Plugboard.Events;

        namespace TestAssembly;

        internal static class SubscriptionExtensions
        {
            extension(IServiceCollection services)
            {
                /// <summary>Subscribes every handler declared in this assembly.</summary>
                internal IServiceCollection AddSubscriptions() => services.AddSubscriptions(static events =>
                {
                    global::TestProject.Orders.OrderHandlers.Subscriptions(events);
                });
            }
        }
        """;

    [Test]
    public async Task Generate_WithEventsOnly_ShouldEmitEventParts()
    {
        GeneratorRun run = await Generate("""
            using Plugboard.Events;

            [Event("thing.changed")]
            public partial class ThingChanged;

            [Event("thing.moved")]
            public readonly partial record struct ThingMoved(int X);

            """ + OrderPlacedEvent);

        Assert.That(run.Files.Keys, Is.EquivalentTo(["Events.g.cs"]));
        Assert.That(run.Files["Events.g.cs"], Is.EqualTo("""
            // <auto-generated/>
            #nullable enable

            partial class ThingChanged : global::Plugboard.Events.IEvent
            {
                public static string EventName => "thing.changed";
            }

            partial record struct ThingMoved : global::Plugboard.Events.IEvent
            {
                public static string EventName => "thing.moved";
            }

            namespace TestProject.Orders
            {
                partial record OrderPlaced : global::Plugboard.Events.IEvent
                {
                    public static string EventName => "order.placed";
                }
            }
            """.ReplaceLineEndings("\n")));
    }

    [Test]
    public async Task Generate_WithTypedHandler_ShouldRewriteSubscribeIntoRegister()
    {
        GeneratorRun run = await Generate(OrderPlacedEvent + """
            namespace TestProject.Orders
            {
                using System.Threading;
                using System.Threading.Tasks;
                using Plugboard.Events;

                public interface IMailer;

                public static class OrderHandlers
                {
                    [Subscribe]
                    public static void Subscriptions(ISubscriptionBuilder events) =>
                        events.Subscribe("send-confirmation", (OrderPlaced e, IMailer mailer, HandlerContext ctx, CancellationToken ct) => Task.CompletedTask);
                }
            }
            """);

        Assert.That(run.Files.Keys, Is.EquivalentTo(["Events.g.cs", "Subscriptions.g.cs", "SubscriptionInterceptors.g.cs"]));
        Assert.That(run.Files["Events.g.cs"], Is.EqualTo(OrderPlacedPart.ReplaceLineEndings("\n")));
        Assert.That(run.Files["Subscriptions.g.cs"], Is.EqualTo(Registration.ReplaceLineEndings("\n")));
        Assert.That(run.Interceptors, Is.EqualTo("""
            [global::System.Runtime.CompilerServices.InterceptsLocation(1, "<location>")]
            public static ISubscriptionBuilder Subscribe0(this ISubscriptionBuilder events, string name, global::System.Delegate handler)
            {
                var typed = (global::System.Func<global::TestProject.Orders.OrderPlaced, global::TestProject.Orders.IMailer, global::Plugboard.Events.HandlerContext, global::System.Threading.CancellationToken, global::System.Threading.Tasks.Task>)handler;
                return events.Register<global::TestProject.Orders.OrderPlaced>(name, null, (e, envelope, ctx, sp, ct) => typed(e, sp.GetRequiredService<global::TestProject.Orders.IMailer>(), ctx, ct));
            }
            """.ReplaceLineEndings("\n")));
    }

    [Test]
    public async Task Generate_WithEnvelopeHandlerMaxDurationAndMethodGroup_ShouldRewriteIntoRegisterAll()
    {
        GeneratorRun run = await Generate(OrderPlacedEvent + """
            namespace TestProject.Audit
            {
                using System;
                using System.Threading;
                using System.Threading.Tasks;
                using Plugboard.Events;

                public sealed class AuditDbContext;

                public static class AuditHandlers
                {
                    [Subscribe]
                    internal static void Subscriptions(ISubscriptionBuilder events) =>
                        events.SubscribeAll("audit", TimeSpan.FromSeconds(90), Audit);

                    private static Task Audit(EventEnvelope envelope, AuditDbContext db, CancellationToken ct) => Task.CompletedTask;
                }
            }
            """);

        Assert.That(run.Interceptors, Is.EqualTo("""
            [global::System.Runtime.CompilerServices.InterceptsLocation(1, "<location>")]
            public static ISubscriptionBuilder SubscribeAll0(this ISubscriptionBuilder events, string name, global::System.TimeSpan maxDuration, global::System.Delegate handler)
            {
                var typed = (global::System.Func<global::Plugboard.Events.EventEnvelope, global::TestProject.Audit.AuditDbContext, global::System.Threading.CancellationToken, global::System.Threading.Tasks.Task>)handler;
                return events.RegisterAll(name, maxDuration, (e, envelope, ctx, sp, ct) => typed(envelope, sp.GetRequiredService<global::TestProject.Audit.AuditDbContext>(), ct));
            }
            """.ReplaceLineEndings("\n")));
    }

    [Test]
    public async Task Generate_WithTwoSubscribeCalls_ShouldEmitOneInterceptorEach()
    {
        GeneratorRun run = await Generate(OrderPlacedEvent + """
            namespace TestProject.Orders
            {
                using System.Threading.Tasks;
                using Plugboard.Events;

                public static class OrderHandlers
                {
                    [Subscribe]
                    public static void Subscriptions(ISubscriptionBuilder events)
                    {
                        events.Subscribe("send-confirmation", (OrderPlaced e) => Task.CompletedTask);
                        events.Subscribe("update-stock", (OrderPlaced e) => Task.CompletedTask);
                    }
                }
            }
            """);

        Assert.That(Regex.Count(run.Files["SubscriptionInterceptors.g.cs"], Regex.Escape("[global::System.Runtime.CompilerServices.InterceptsLocation(")), Is.EqualTo(2));
        Assert.That(run.Files["SubscriptionInterceptors.g.cs"], Does.Contain("Subscribe0(").And.Contain("Subscribe1("));
    }

    [Test]
    public async Task Generate_WithInvalidHandler_ShouldEmitRegistrationButNoInterceptor()
    {
        GeneratorRun run = await Generate(OrderPlacedEvent + """
            namespace TestProject.Orders
            {
                using System.Threading.Tasks;
                using Plugboard.Events;

                public static class OrderHandlers
                {
                    [Subscribe]
                    public static void Subscriptions(ISubscriptionBuilder events) =>
                        events.Subscribe("broken", (OrderPlaced e, string reason) => Task.CompletedTask);
                }
            }
            """);

        Assert.That(run.Files.Keys, Is.EquivalentTo(["Events.g.cs", "Subscriptions.g.cs"]));
    }

    [Test]
    public async Task Generate_WithInvalidSubscribeMethod_ShouldNotRegisterIt()
    {
        GeneratorRun run = await Generate(OrderPlacedEvent + """
            namespace TestProject.Orders
            {
                using Plugboard.Events;

                public static class OrderHandlers
                {
                    [Subscribe]
                    public static int Subscriptions(ISubscriptionBuilder events) => 0;
                }
            }
            """);

        Assert.That(run.Files.Keys, Is.EquivalentTo(["Events.g.cs"]));
    }

    [Test]
    public async Task Generate_WithNothingMarked_ShouldEmitNothing()
    {
        GeneratorRun run = await Generate("""
            namespace TestProject
            {
                public class SomeClass { }
            }
            """);

        Assert.That(run.Files, Is.Empty);
    }

    [Test]
    public async Task Generate_WithRootNamespaceProperty_ShouldEmitRegistrationIntoRootNamespace()
    {
        GeneratorRun run = await Generate(OrderPlacedEvent + """
            namespace TestProject.Orders
            {
                using Plugboard.Events;

                public static class OrderHandlers
                {
                    [Subscribe]
                    public static void Subscriptions(ISubscriptionBuilder events) { }
                }
            }
            """, rootNamespace: "My.Custom.Root");

        Assert.That(run.Files["Subscriptions.g.cs"], Does.Contain("namespace My.Custom.Root;"));
    }

    /// <summary>Generated files by hint name, and the interceptor bodies with the opaque location replaced by a placeholder.</summary>
    private sealed record GeneratorRun(IReadOnlyDictionary<string, string> Files)
    {
        public string Interceptors => Files.TryGetValue("SubscriptionInterceptors.g.cs", out string? text)
            ? string.Join("\n", Regex.Replace(text, """InterceptsLocation\(1, "[^"]+"\)""", """InterceptsLocation(1, "<location>")""")
                .Split('\n')
                .SkipWhile(static line => !line.Contains("[global::System.Runtime.CompilerServices.InterceptsLocation(", StringComparison.Ordinal))
                .TakeWhile(static line => line != "    }")
                .Select(static line => line.Length > 8 ? line[8..] : line.TrimStart()))
            : string.Empty;
    }

    [AssertionMethod]
    private static async Task<GeneratorRun> Generate(string source, string rootNamespace = "TestAssembly")
    {
        ImmutableArray<MetadataReference> references = await TestReferences.Net100.ResolveAsync(LanguageNames.CSharp, CancellationToken.None);
        var parseOptions = CSharpParseOptions.Default.WithFeatures([new KeyValuePair<string, string>("InterceptorsNamespaces", "Plugboard.Events.Generated")]);
        var compilation = CSharpCompilation.Create("TestAssembly",
            [CSharpSyntaxTree.ParseText(source, parseOptions)],
            [.. references, MetadataReference.CreateFromFile(typeof(EventAttribute).Assembly.Location), MetadataReference.CreateFromFile(typeof(IServiceCollection).Assembly.Location)],
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, nullableContextOptions: NullableContextOptions.Enable));

        GeneratorDriver driver = CSharpGeneratorDriver.Create(
            [new EventGenerator().AsSourceGenerator()],
            parseOptions: parseOptions,
            optionsProvider: new RootNamespaceOptions(rootNamespace));
        driver = driver.RunGeneratorsAndUpdateCompilation(compilation, out Compilation output, out ImmutableArray<Diagnostic> generatorDiagnostics, CancellationToken.None);

        Assert.That(generatorDiagnostics, Is.Empty);
        // The source under test may be deliberately invalid (PB rules); generated code must compile without even a warning,
        // because consumers build with TreatWarningsAsErrors.
        Diagnostic[] generated = [.. output.GetDiagnostics().Where(static d =>
            d.Severity >= DiagnosticSeverity.Warning && d.Location.SourceTree?.FilePath.EndsWith(".g.cs", StringComparison.Ordinal) == true)];
        Assert.That(generated, Is.Empty);

        GeneratorDriverRunResult result = driver.GetRunResult();
        var files = result.Results.Single().GeneratedSources
            .ToDictionary(static s => s.HintName, static s => s.SourceText.ToString().ReplaceLineEndings("\n"), StringComparer.Ordinal);
        return new GeneratorRun(files);
    }

    /// <summary>build_property.RootNamespace as MSBuild passes it to the generator.</summary>
    private sealed class RootNamespaceOptions(string rootNamespace) : AnalyzerConfigOptionsProvider
    {
        public override AnalyzerConfigOptions GlobalOptions { get; } = new Options(rootNamespace);

        public override AnalyzerConfigOptions GetOptions(SyntaxTree tree) => GlobalOptions;

        public override AnalyzerConfigOptions GetOptions(AdditionalText textFile) => GlobalOptions;

        private sealed class Options(string rootNamespace) : AnalyzerConfigOptions
        {
            public override bool TryGetValue(string key, out string value)
            {
                value = rootNamespace;
                return key == "build_property.RootNamespace";
            }
        }
    }
}
